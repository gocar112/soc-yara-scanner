"""What to do about a finding, from authoritative sources where they exist.

Two kinds of finding need two kinds of answer.

A finding carrying a CVE - every rule generated by rulegen.py does - has an
authoritative answer already written down. CISA's Known Exploited
Vulnerabilities catalogue publishes `cisaRequiredAction`, the mandated
remediation text, with a due date; NVD carries vendor references tagged Patch or
Vendor Advisory. Neither needs to be invented or searched for.

A malware finding has no CVE and no vendor patch. What it has is a response
shape that depends on what was found: a web shell means credentials are
suspect and web logs need reading; ransomware means isolate before anything
else. Those are playbooks, and they are written here rather than fetched,
because they do not change per incident.

Nothing here is generated text presented as advice. Where the answer is known it
is quoted from its source with attribution; where it is not, the playbook says
what class of response applies and leaves the judgement to the analyst.
"""
