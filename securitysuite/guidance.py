class Guidance:
    """Assembles remediation guidance, caching the CVE lookups."""

    def __init__(self, cache_dir: str, nvd=None):
        self.cache_dir = Path(cache_dir)
        self.nvd = nvd
        self._lock = threading.Lock()
        self.cache_dir.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------ cves
    @staticmethod
    def cve_ids(finding: dict) -> list:
        """CVEs named by the rules that fired, or extracted from the file."""
        found = []
        for match in finding.get("matches", []) or []:
            value = str((match.get("meta") or {}).get("cve") or "")
            for cve in CVE_RE.findall(value):
                if cve.upper() not in found:
                    found.append(cve.upper())
        for indicator in (finding.get("iocs") or {}).get("indicators", []) or []:
            if indicator.get("type") == "cve":
                cve = str(indicator.get("value", "")).upper()
                if cve and cve not in found:
                    found.append(cve)
        return found[:8]

    def _cve_detail(self, cve_id: str) -> dict:
        cached = self.cache_dir / (cve_id + ".json")
        if cached.exists():
            try:
                detail = json.loads(cached.read_text(encoding="utf-8"))
                if detail.get("schema") == GUIDANCE_SCHEMA:
                    return detail
            except (OSError, json.JSONDecodeError):
                pass
        if self.nvd is None:
            return {"id": cve_id, "error": "no NVD client configured"}

        try:
            record = self.nvd.fetch_cve(cve_id)
        except Exception as exc:
            return {"id": cve_id, "error": str(exc)}
        if record.get("error"):
            return {"id": cve_id, "error": record.get("error")}

        detail = {
            "schema": GUIDANCE_SCHEMA,
            "id": cve_id,
            "kev": bool(record.get("kev")),
            "kev_name": record.get("kev_name", ""),
            "required_action": record.get("kev_required_action", ""),
            "action_due": record.get("kev_action_due", ""),
            "exploit_added": record.get("exploit_added", ""),
            "patch_refs": (record.get("patch_refs") or [])[:8],
            "fetched_at": now_iso(),
        }
        try:
            cached.write_text(json.dumps(detail, indent=1), encoding="utf-8")
        except OSError:
            pass
        return detail

    # -------------------------------------------------------------- playbooks
    @staticmethod
    def playbook_for(finding: dict) -> dict:
        """Namespace, then rule name, then tag, then default.

        Rule names are consulted before tags because a rule's *subject* is a
        better guide than its category: `Ransom_Note_Template` lives in the
        `windows_threats` namespace and carries the tag `malware`, neither of
        which says ransomware. Matching the name gets the right playbook.
        """
        namespaces, tags, names = [], [], []
        for match in finding.get("matches", []) or []:
            namespaces.append(str(match.get("namespace") or "").lower())
            tags.extend(str(t).lower() for t in (match.get("tags") or []))
            names.append(str(match.get("rule") or "").lower())
        names.extend(str(r).lower() for r in finding.get("rule_names", []) or [])

        # Rule name first. `windows_threats` is a catch-all holding ransom-note,
        # credential-dumping and PowerShell rules alike, so its namespace says
        # far less than the rule's own name does.
        for keyword, key in RULE_KEYWORDS:
            if any(keyword in name for name in names):
                return dict(PLAYBOOKS[key], source="rule:*" + keyword + "*")

        for key in namespaces:
            if key in PLAYBOOKS:
                return dict(PLAYBOOKS[key], source="namespace:" + key)

        for key in tags:
            if key in PLAYBOOKS:
                return dict(PLAYBOOKS[key], source="tag:" + key)
            mapped = TAG_ALIASES.get(key)
            if mapped:
                return dict(PLAYBOOKS[mapped], source="tag:" + key)

        return dict(DEFAULT_PLAYBOOK, source="default")

    # ------------------------------------------------------------------- main
    def for_finding(self, finding: dict) -> dict:
        cves = self.cve_ids(finding)
        details = [self._cve_detail(c) for c in cves]
        kev = [d for d in details if d.get("kev")]
        return {
            "finding": finding.get("id"),
            "file_name": finding.get("file_name"),
            "severity": finding.get("severity"),
            "playbook": self.playbook_for(finding),
            "cves": details,
            "kev_count": len(kev),
            "required_actions": [
                {"cve": d["id"], "action": d["required_action"],
                 "due": d.get("action_due", "")}
                for d in kev if d.get("required_action")
            ],
            "patch_refs": [r for d in details for r in d.get("patch_refs", [])][:12],
            "generated_at": now_iso(),
        }
